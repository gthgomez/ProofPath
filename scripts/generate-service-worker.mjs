#!/usr/bin/env node
/**
 * Generate the offline shell service worker for the exported web build.
 *
 * `expo export --platform web` copies `public/` into `dist/` but has no
 * service-worker step. This script runs after the export, indexes the app shell
 * (everything except the large sandbox runtimes), and writes `dist/sw.js` with a
 * content-derived cache version.
 *
 * Sandbox WASM/compiler assets are deliberately excluded from precache: they are
 * large and many learners never open every language. They are cached at runtime
 * the first time a lesson uses them, so offline execution works after that first
 * online use.
 */
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const DIST = process.env.E2E_DIST ?? "dist";

if (!existsSync(join(DIST, "index.html"))) {
  console.error(`No web export found at ${DIST}/index.html. Run: npx expo export --platform web`);
  process.exit(2);
}

const PRECACHE_EXTENSIONS = new Set([
  ".html", ".js", ".css", ".json", ".png", ".jpg", ".jpeg", ".svg", ".webp", ".gif",
  ".woff", ".woff2", ".ttf", ".otf", ".ico", ".txt"
]);

function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(full));
    } else {
      files.push(full);
    }
  }
  return files;
}

const files = walk(DIST)
  .map((file) => ({
    path: `/${relative(DIST, file).split(sep).join("/")}`,
    size: statSync(file).size,
    extension: file.slice(file.lastIndexOf(".")).toLowerCase()
  }))
  .filter((file) => file.path !== "/sw.js")
  .filter((file) => !file.path.startsWith("/sandbox-assets/"))
  .filter((file) => PRECACHE_EXTENSIONS.has(file.extension))
  .sort((left, right) => left.path.localeCompare(right.path));

const version = createHash("sha256")
  .update(JSON.stringify(files.map((file) => [file.path, file.size])))
  .digest("hex")
  .slice(0, 12);

const precache = ["/", "/index.html", ...files.map((file) => file.path).filter((path) => path !== "/index.html")];
const precacheJson = JSON.stringify(Array.from(new Set(precache)), null, 2);

const source = `/* Generated by scripts/generate-service-worker.mjs. Do not edit by hand. */
"use strict";

const VERSION = ${JSON.stringify(version)};
const CACHE = "proofpath-shell-" + VERSION;
const PRECACHE = ${precacheJson};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then(async (cache) => {
        // Best effort: one missing optional asset must not block the install.
        await Promise.all(PRECACHE.map((url) => cache.add(new Request(url, { cache: "reload" })).catch(() => undefined)));
      })
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((key) => key.startsWith("proofpath-shell-") && key !== CACHE)
        .map((key) => caches.delete(key))
    );
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === "/sw.js") return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        const cache = await caches.open(CACHE);
        // Keep the SPA shell current for the next offline launch.
        cache.put("/index.html", response.clone());
        return response;
      } catch {
        const cache = await caches.open(CACHE);
        return (await cache.match("/index.html")) || (await cache.match("/")) || Response.error();
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(request);
    if (cached) return cached;

    try {
      const response = await fetch(request);
      if (response.ok && response.type === "basic") {
        cache.put(request, response.clone());
      }
      return response;
    } catch {
      return cached || Response.error();
    }
  })());
});
`;

writeFileSync(join(DIST, "sw.js"), source);
console.log(`Generated ${join(DIST, "sw.js")} (version ${version}, ${precache.length} precached paths)`);

#!/usr/bin/env node
/**
 * Generate the offline shell service worker for the exported web build.
 *
 * Design:
 * - The version is derived from file *contents*, not paths or sizes.
 * - Every precached asset (including Pyodide/sql.js/TypeScript runtimes) must be
 *   fetched successfully before the new worker can activate. A partial install
 *   fails and leaves the previous working cache untouched.
 * - A new worker only activates after its complete cache exists, then removes
 *   older `proofpath-` caches.
 * - Navigation responses are only written to the shell cache when they are
 *   successful HTML; an error page can never replace the offline shell.
 *
 * The runtime assets are included deliberately: a shell that updates but leaves
 * an older Pyodide/sql.js/TypeScript cache would mix versions.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const DIST = process.env.E2E_DIST ?? "dist";

if (!existsSync(join(DIST, "index.html"))) {
  console.error(`No web export found at ${DIST}/index.html. Run: npx expo export --platform web`);
  process.exit(2);
}

const PRECACHE_EXTENSIONS = new Set([
  ".html", ".js", ".mjs", ".css", ".json", ".png", ".jpg", ".jpeg", ".svg", ".webp", ".gif",
  ".woff", ".woff2", ".ttf", ".otf", ".ico", ".wasm", ".data", ".zip", ".whl"
]);

function walk(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(full));
    } else {
      files.push(full);
    }
  }
  return files;
}

const files = walk(DIST)
  .map((file) => {
    const path = `/${relative(DIST, file).split(sep).join("/")}`;
    return { path, file, extension: file.slice(file.lastIndexOf(".")).toLowerCase() };
  })
  .filter((file) => file.path !== "/sw.js")
  .filter((file) => PRECACHE_EXTENSIONS.has(file.extension))
  .sort((left, right) => left.path.localeCompare(right.path));

const contentHash = createHash("sha256");
for (const file of files) {
  contentHash.update(file.path);
  contentHash.update("\0");
  contentHash.update(readFileSync(file.file));
  contentHash.update("\0");
}
const version = contentHash.digest("hex").slice(0, 16);
const precache = Array.from(new Set(["/", "/index.html", ...files.map((file) => file.path)]));
const precacheJson = JSON.stringify(precache, null, 2);

const source = `/* Generated by scripts/generate-service-worker.mjs. Do not edit by hand. */
"use strict";

const VERSION = ${JSON.stringify(version)};
const CACHE = "proofpath-shell-" + VERSION;
const PRECACHE = ${precacheJson};

async function precacheAll(cache) {
  // all-or-nothing: any failed required asset aborts the install so the
  // previous worker and its complete cache remain active.
  for (const url of PRECACHE) {
    const response = await fetch(new Request(url, { cache: "reload" }));
    if (!response || !response.ok) {
      throw new Error("Required offline asset failed: " + url + " (" + (response ? response.status : "no response") + ")");
    }
    await cache.put(url, response);
  }
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    // A retry after a failed install must not reuse a partial cache.
    await caches.delete(CACHE);
    const cache = await caches.open(CACHE);
    try {
      await precacheAll(cache);
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
    // Only a complete cache reaches this point. The old worker keeps control
    // until activation, so a failed install cannot break the current offline app.
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys
        .filter((key) => key.startsWith("proofpath-shell-") && key !== CACHE)
        .map((key) => caches.delete(key))
    );
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === "/sw.js") return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const response = await fetch(request);
        const contentType = response.headers.get("content-type") || "";
        if (response.ok && contentType.includes("text/html")) {
          cache.put("/index.html", response.clone());
        }
        return response;
      } catch {
        return (await cache.match("/index.html")) || (await cache.match("/")) || Response.error();
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(request);
    if (cached) return cached;

    try {
      const response = await fetch(request);
      // Cache successful same-origin assets in this version's cache only.
      if (response.ok && response.type === "basic") {
        cache.put(request, response.clone());
      }
      return response;
    } catch {
      return cached || Response.error();
    }
  })());
});
`;

writeFileSync(join(DIST, "sw.js"), source);
console.log(`Generated ${join(DIST, "sw.js")} (version ${version}, ${precache.length} precached paths)`);
